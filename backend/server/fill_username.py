async def main():
    session = await db_session()
    repo = TherapistRepo(session=session)
    for id in therapist_ids:
        therapist = await repo.select_by_tg_id(tg_id=id)
        contacts_for_client = therapist.contacts_for_client
        result_username = ""
        flag = False
        if contacts_for_client:
            for char in contacts_for_client:
                if char == "@":
                    flag=True
                    continue
                
                if flag and char != " " and char != "\n":
                    result_username += char
                
                if (char == " " or char == "\n") and flag:
                    break
            if result_username:
                await repo.update_username(tg_id=id, username=result_username)
                

    await session.commit()
    await session.close()

asyncio.run(main())